// Extração segura de Localização (bairro e cidade a partir de endereco)
export const parseAddress = (addressStr) => {
  // "R. Nilza Medeiros Martins, 187 - Jardim Colombo, São Paulo - SP, 05628-010, Brasil"
  const parts = addressStr.split("-").map(p => p.trim());
  const street = parts[0] || "R. Nilza Medeiros Martins, 187";
  const neighborhoodPart = parts[1] ? parts[1].split(",")[0].trim() : "Jardim Colombo";
  const cityStatePart = parts[1] && parts[1].includes(",") ? parts[1].split(",")[1].trim() : (parts[2] ? parts[2].split(",")[0].trim() : "São Paulo - SP");
  const cepMatch = addressStr.match(/\d{5}-\d{3}/);

  return {
    street: street,
    neighborhood: neighborhoodPart || "Jardim Colombo",
    cityState: cityStatePart || "São Paulo - SP",
    city: "São Paulo",
    state: "SP",
    postalCode: cepMatch ? cepMatch[0] : "05628-010",
    country: "BR"
  };
};

