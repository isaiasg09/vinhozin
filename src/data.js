// Utilitário para verificar status de funcionamento atual em America/Sao_Paulo
export const getScheduleStatus = () => {
  try {
    const spTimeStr = new Intl.DateTimeFormat("en-US", {
      timeZone: "America/Sao_Paulo",
      hour: "numeric",
      minute: "numeric",
      hour12: false,
      weekday: "short"
    }).format(new Date());

    const now = new Date();
    const formatter = new Intl.DateTimeFormat("en-US", {
      timeZone: "America/Sao_Paulo",
      hour: "numeric",
      minute: "numeric",
      hour12: false
    });
    const parts = formatter.formatToParts(now);
    const hour = parseInt(parts.find(p => p.type === "hour")?.value || "0", 10);
    const minute = parseInt(parts.find(p => p.type === "minute")?.value || "0", 10);
    const totalMinutes = hour * 60 + minute;

    const dayFormatter = new Intl.DateTimeFormat("en-US", {
      timeZone: "America/Sao_Paulo",
      weekday: "short"
    });
    const weekday = dayFormatter.format(now); // Sun, Mon, Tue, Wed, Thu, Fri, Sat

    // Horários reais:
    // Terça a Sexta: 13:00 - 19:00 (780 - 1140 min)
    // Sábado: 10:00 - 14:00 (600 - 840 min)
    // Domingo e Segunda: Fechado
    let isOpen = false;
    let nextOpenText = "Aberto de Terça a Sexta às 13h";

    if (["Tue", "Wed", "Thu", "Fri"].includes(weekday)) {
      if (totalMinutes >= 780 && totalMinutes < 1140) {
        isOpen = true;
      }
    } else if (weekday === "Sat") {
      if (totalMinutes >= 600 && totalMinutes < 840) {
        isOpen = true;
      }
    }

    return {
      isOpen,
      statusLabel: isOpen ? "Aberto agora" : "Fechado no momento",
      scheduleHint: isOpen ? "Atendimento presencial até às 19h" : "Consulte disponibilidade e atendimento no WhatsApp"
    };
  } catch {
    return {
      isOpen: false,
      statusLabel: "Consulte horários",
      scheduleHint: "Atendimento no WhatsApp disponível"
    };
  }
};
